import json
from pathlib import Path
import shutil

import cv2 as cv


DATASET_DIR = Path(__file__).with_name("blue_led_dataset")
IMAGE_DIR = DATASET_DIR / "images"
LABEL_DIR = DATASET_DIR / "labels"
BACKUP_DIR = DATASET_DIR / "labels_autogenerated"
MANIFEST_PATH = DATASET_DIR / "review_manifest.json"
WINDOW_NAME = "Review blue LED labels"
MAX_DISPLAY_WIDTH = 1200
MAX_DISPLAY_HEIGHT = 850
BOX_PADDING = 2


def load_manifest():
    if not MANIFEST_PATH.is_file():
        return set()
    data = json.loads(MANIFEST_PATH.read_text(encoding="utf-8"))
    return set(data.get("reviewed", []))


def save_manifest(reviewed):
    temporary_path = MANIFEST_PATH.with_suffix(".json.tmp")
    temporary_path.write_text(
        json.dumps({"reviewed": sorted(reviewed)}, indent=2) + "\n",
        encoding="utf-8",
    )
    temporary_path.replace(MANIFEST_PATH)


def write_labels(label_path, boxes, image_width, image_height):
    rows = []
    for x1, y1, x2, y2 in boxes:
        x1, x2 = sorted(
            (
                max(0, min(image_width, x1)),
                max(0, min(image_width, x2)),
            )
        )
        y1, y2 = sorted(
            (
                max(0, min(image_height, y1)),
                max(0, min(image_height, y2)),
            )
        )
        if x2 <= x1 or y2 <= y1:
            continue

        center_x = (x1 + x2) / (2 * image_width)
        center_y = (y1 + y2) / (2 * image_height)
        width = (x2 - x1) / image_width
        height = (y2 - y1) / image_height
        rows.append(
            f"0 {center_x:.6f} {center_y:.6f} {width:.6f} {height:.6f}"
        )
    label_path.write_text("\n".join(rows) + ("\n" if rows else ""), encoding="utf-8")


def mouse_callback(event, x, y, flags, state):
    image_x = round(x / state["scale"])
    image_y = round(y / state["scale"])

    if event == cv.EVENT_LBUTTONDOWN:
        state["start"] = (image_x, image_y)
        state["drag_end"] = (image_x, image_y)
    elif (
        event == cv.EVENT_MOUSEMOVE
        and state["start"] is not None
        and flags & cv.EVENT_FLAG_LBUTTON
    ):
        state["drag_end"] = (image_x, image_y)
    elif event == cv.EVENT_LBUTTONUP and state["start"] is not None:
        start_x, start_y = state["start"]
        end_x, end_y = image_x, image_y
        x1, x2 = sorted((start_x, end_x))
        y1, y2 = sorted((start_y, end_y))
        if x2 - x1 >= 2 and y2 - y1 >= 2:
            state["boxes"].append(
                (
                    max(0, x1 - BOX_PADDING),
                    max(0, y1 - BOX_PADDING),
                    x2 + BOX_PADDING,
                    y2 + BOX_PADDING,
                )
            )
        state["start"] = None
        state["drag_end"] = None


def render_frame(frame, boxes, index, total, status, scale, state):
    display = cv.resize(
        frame,
        None,
        fx=scale,
        fy=scale,
        interpolation=cv.INTER_AREA if scale < 1 else cv.INTER_LINEAR,
    )
    for x1, y1, x2, y2 in boxes:
        cv.rectangle(
            display,
            (round(x1 * scale), round(y1 * scale)),
            (round(x2 * scale), round(y2 * scale)),
            (0, 255, 0),
            2,
        )
    if state["start"] is not None and state["drag_end"] is not None:
        cv.rectangle(
            display,
            tuple(round(value * scale) for value in state["start"]),
            tuple(round(value * scale) for value in state["drag_end"]),
            (0, 255, 255),
            2,
        )

    cv.putText(
        display,
        f"Frame {index + 1}/{total} | boxes: {len(boxes)} | {status}",
        (10, 25),
        cv.FONT_HERSHEY_SIMPLEX,
        0.6,
        (255, 255, 255),
        2,
    )
    cv.putText(
        display,
        "Drag tight boxes around LED | U: undo | C: clear | Enter: save | N: no LED",
        (10, 52),
        cv.FONT_HERSHEY_SIMPLEX,
        0.5,
        (255, 255, 255),
        2,
    )
    cv.putText(
        display,
        "Q: quit and resume later",
        (10, 77),
        cv.FONT_HERSHEY_SIMPLEX,
        0.5,
        (255, 255, 255),
        2,
    )
    return display


def main():
    images = sorted(
        image
        for split in ("train", "val")
        for image in (IMAGE_DIR / split).glob("*.jpg")
    )
    if not images:
        raise FileNotFoundError(f"No captured images found in {IMAGE_DIR}.")

    reviewed = load_manifest()
    remaining = [
        image
        for image in images
        if image.relative_to(IMAGE_DIR).as_posix() not in reviewed
    ]
    if not remaining:
        print(f"All {len(images)} images have been reviewed.")
        return

    cv.namedWindow(WINDOW_NAME, cv.WINDOW_AUTOSIZE)
    state = {"boxes": [], "start": None, "drag_end": None, "scale": 1.0}
    cv.setMouseCallback(WINDOW_NAME, mouse_callback, state)

    try:
        for image_path in remaining:
            frame = cv.imread(str(image_path))
            if frame is None:
                raise RuntimeError(f"Could not read dataset image: {image_path}")

            image_height, image_width = frame.shape[:2]
            state["scale"] = min(
                1.0,
                MAX_DISPLAY_WIDTH / image_width,
                MAX_DISPLAY_HEIGHT / image_height,
            )
            state["boxes"] = []
            state["start"] = None
            state["drag_end"] = None
            relative_path = image_path.relative_to(IMAGE_DIR).as_posix()

            while True:
                display = render_frame(
                    frame,
                    state["boxes"],
                    len(reviewed) + 1,
                    len(images),
                    relative_path,
                    state["scale"],
                    state,
                )
                cv.imshow(WINDOW_NAME, display)
                key = cv.waitKey(20) & 0xFF

                if key in (ord("q"), ord("Q"), 27):
                    return
                if key in (ord("u"), ord("U"), 8, 127):
                    if state["boxes"]:
                        state["boxes"].pop()
                elif key in (ord("c"), ord("C")):
                    state["boxes"].clear()
                elif key in (ord("n"), ord("N")):
                    state["boxes"].clear()
                    label_path = LABEL_DIR / image_path.relative_to(IMAGE_DIR).with_suffix(
                        ".txt"
                    )
                    save_reviewed_image(
                        image_path,
                        label_path,
                        state["boxes"],
                        reviewed,
                        relative_path,
                        image_width,
                        image_height,
                    )
                    break
                elif key in (10, 13, 32):
                    if not state["boxes"]:
                        print(
                            f"{relative_path}: draw at least one box or press N "
                            "if the LED is absent."
                        )
                        continue
                    label_path = LABEL_DIR / image_path.relative_to(IMAGE_DIR).with_suffix(
                        ".txt"
                    )
                    save_reviewed_image(
                        image_path,
                        label_path,
                        state["boxes"],
                        reviewed,
                        relative_path,
                        image_width,
                        image_height,
                    )
                    break
    finally:
        cv.destroyAllWindows()


def save_reviewed_image(
    image_path, label_path, boxes, reviewed, relative_path, image_width, image_height
):
    autogenerated_label = label_path
    backup_label = BACKUP_DIR / image_path.relative_to(IMAGE_DIR).with_suffix(".txt")
    if autogenerated_label.is_file() and not backup_label.exists():
        backup_label.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(autogenerated_label, backup_label)

    label_path.parent.mkdir(parents=True, exist_ok=True)
    write_labels(label_path, boxes, image_width, image_height)
    reviewed.add(relative_path)
    save_manifest(reviewed)
    print(f"Reviewed {relative_path}: {len(boxes)} LED box(es)")


if __name__ == "__main__":
    main()
